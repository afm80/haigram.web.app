}

String tr(String ar) => AppLang.isEn ? (_en[ar] ?? ar) : ar;

/// نص بمتغيرات: المفتاح فيه {0} و{1}... بدل المتغيرات، وتُستبدل بالقيم عند العرض.
String trf(String ar, List<Object?> args) {
  var s = tr(ar);
  for (var i = 0; i < args.length; i++) {
    s = s.replaceAll('{$i}', '${args[i]}');
  }
  return s;
}

